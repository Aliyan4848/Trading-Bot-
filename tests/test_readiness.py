def test_load_summaries_skips_the_aggregate_and_survives_broken_files(cfg, tmp_path):
    results = tmp_path / "results"
    write_run(results, "EURUSD")
    (results / "portfolio_20240101_120000_report.json").write_text("{}", encoding="utf-8")
    (results / "BROKEN_report.json").write_text("{not json", encoding="utf-8")
    summaries = load_result_summaries(results)
    assert [s["symbol"] for s in summaries] == ["EURUSD"]
    assert load_result_summaries(results / "missing") == []


def test_report_renders_and_serialises(cfg, tmp_path):
    for symbol in ("EURUSD", "GBPUSD", "XAUUSD"):
        write_run(tmp_path / "results", symbol, synthetic=True)
    report = assess_readiness(cfg)
    text = format_report(report)
    assert "NOT READY" in text and "Go-live readiness" in text
    payload = report.to_dict()
    assert payload["verdict"] == "NOT READY"
    assert payload["counts"]["fail"] >= 1
    assert json.dumps(payload)  # must be serialisable for --json
    assert set(payload["checks"][0]) == {"key", "label", "status", "detail", "fix"}


def test_cli_readiness_reports_and_exits_nonzero_while_blocked(cfg, tmp_path, capsys, monkeypatch):
    from scalper import cli

    for symbol in ("EURUSD", "GBPUSD"):
        write_run(tmp_path / "results", symbol, synthetic=True, expectancy_r=-0.2)
    code = cli.main(["readiness", "--results-dir", str(tmp_path / "results")])
    assert code == 1, "a blocked deployment must be a non-zero exit for scripts"
    out = capsys.readouterr().out
    assert "NOT READY" in out and "[FAIL]" in out


def test_cli_readiness_exits_zero_when_every_gate_passes(cfg, tmp_path, capsys):
    from scalper import cli

    results = tmp_path / "results"
    for symbol in ("EURUSD", "GBPUSD", "XAUUSD"):
        write_run(results, symbol, expectancy_r=0.08, profit_factor=1.5, days=800)
    (results / "sweep_x.csv").write_text("a\n1\n", encoding="utf-8")
    code = cli.main(["readiness", "--results-dir", str(results), "--json"])
    assert code == 0
    out = capsys.readouterr().out
    assert "READY" in out and '"verdict"' in out
