def test_real_data_with_a_consistent_edge_can_pass(cfg, tmp_path):
    results = tmp_path / "results"
    for symbol in ("EURUSD", "GBPUSD", "XAUUSD"):
        write_run(results, symbol, expectancy_r=0.08, profit_factor=1.5, days=800)
    (results / "sweep_20240101_120000.csv").write_text("fast_ema,expectancy_r\n9,0.08\n", encoding="utf-8")
    report = assess_readiness(cfg)
    assert report.failures == []
    assert report.warnings == [], [c.detail for c in report.warnings]
    assert report.verdict.startswith("READY")
    # Even a pass keeps the disclaimer: a checklist is not a forecast.
    assert "not a prediction" in report.disclaimer
    assert "forecast" not in report.disclaimer.split("It is")[0]


def test_missing_out_of_sample_evidence_blocks_a_full_pass(cfg, tmp_path):
    for symbol in ("EURUSD", "GBPUSD"):
        write_run(tmp_path / "results", symbol, expectancy_r=0.08, profit_factor=1.5, days=800)
    report = assess_readiness(cfg)
    assert status_of(report, "oos") is WARN
    assert report.verdict == "PROBABLY NOT READY"
    assert "optimize.py" in report.next_action()


def test_drawdown_overshoot_is_called_out(cfg, tmp_path):
    write_run(tmp_path / "results", "EURUSD", max_drawdown_pct=12.3)
    write_run(tmp_path / "results", "GBPUSD", max_drawdown_pct=4.0)
    report = assess_readiness(cfg)
    assert status_of(report, "dd") is WARN
    assert "overshoot" in next(c.detail for c in report.checks if c.key == "dd")


