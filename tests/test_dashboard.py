def test_module_imports_without_a_streamlit_runtime(app):
    """Importing the app must have no side effects (no UI calls at module level)."""
    assert callable(app.render)
    assert callable(app.load_runs)


def test_discover_ignores_portfolio_files_and_missing_directory(app, results_dir):
    found = app.discover(results_dir)
    assert {p.name for p in found} == {"EURUSD_ema_rsi_momentum_M1_report.json",
                                       "XAUUSD_bollinger_reversion_M1_report.json"}
    (results_dir / "portfolio_20240101.csv").write_text("x", encoding="utf-8")
    (results_dir / "portfolio_20240101_report.json").write_text("{}", encoding="utf-8")
    assert len(app.discover(results_dir)) == 2
    assert app.discover(results_dir / "does-not-exist") == []


def test_load_run_pulls_in_siblings_and_flags_synthetic_data(app, results_dir):
    run = app.load_run(results_dir / "EURUSD_ema_rsi_momentum_M1_report.json")
    assert (run.symbol, run.strategy, run.timeframe) == ("EURUSD", "ema_rsi_momentum", "M1")
    assert run.label == "EURUSD · ema_rsi_momentum · M1"
    assert run.total_trades == 1
    assert run.net_profit == pytest.approx(106.5)
    assert run.is_synthetic is True
    assert run.trades is not None and len(run.trades) == 1
    # Timestamps are parsed to UTC datetimes, not left as strings, so charts work.
    assert str(run.trades["entry_time"].dtype).startswith("datetime64")
    assert run.equity is not None and len(run.equity) == 2

    other = app.load_run(results_dir / "XAUUSD_bollinger_reversion_M1_report.json")
    assert other.is_synthetic is False
    assert other.trades is None, "no trades CSV on disk -> None, not an empty crash"


def test_row_missing_files_do_not_explode(app, tmp_path):
    lone = tmp_path / "EURUSD_ema_rsi_momentum_M1_report.json"
    lone.write_text(json.dumps({"symbol": "EURUSD", "metrics": {}}), encoding="utf-8")
    run = app.load_run(lone)
    assert run.trades is None and run.equity is None
    assert run.net_profit == 0.0
    table = app.comparison_table([run])
    assert list(table["symbol"]) == ["EURUSD"]
    assert table["synthetic"].iloc[0] == False  # noqa: E712 - pandas bool, not a bool


def test_comparison_table_has_one_row_per_run(app, results_dir):
    runs = app.load_runs(results_dir)
    table = app.comparison_table(runs)
    assert len(table) == 2
    assert set(table["symbol"]) == {"EURUSD", "XAUUSD"}
    assert table["net_profit"].sum() == pytest.approx(106.5)
    assert list(table.columns)[:4] == ["symbol", "strategy", "timeframe", "trades"]


def test_equity_frame_stacks_runs_for_charting(app, results_dir):
    runs = app.load_runs(results_dir)
    frame = app.equity_frame(runs)
    assert set(frame["run"]) == {r.label for r in runs}
    assert frame["time"].is_monotonic_increasing is False or True  # order is not promised
    assert len(frame) == 4
    assert app.equity_frame([]).empty


def test_monthly_returns_frame_uses_each_runs_own_start(app, results_dir):
    runs = app.load_runs(results_dir)
    frame = app.monthly_returns_frame(runs)
    assert set(frame["period"]) == {"2024-01"}
    eur = frame[frame["run"].str.startswith("EURUSD")].iloc[0]
    xau = frame[frame["run"].str.startswith("XAUUSD")].iloc[0]
    assert eur["return_pct"] == pytest.approx(1.065, abs=0.01)   # 10,000 -> 10,106.50
    assert xau["return_pct"] == pytest.approx(-1.0, abs=0.01)    # 10,000 -> 9,900
    assert app.monthly_returns_frame([]).empty


def test_broken_json_degrades_instead_of_raising(app, tmp_path):
    bad = tmp_path / "EURUSD_ema_rsi_momentum_M1_report.json"
    bad.write_text("{not json at all", encoding="utf-8")
    run = app.load_run(bad)
    assert run.metrics == {} and run.net_profit == 0.0


