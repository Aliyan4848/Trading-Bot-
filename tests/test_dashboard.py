def test_cli_dashboard_explains_the_extra_when_streamlit_is_absent(monkeypatch, capsys):
    """A missing optional dependency must produce instructions, not a traceback."""
    import importlib.util as util

    from scalper import cli

    real_find_spec = util.find_spec
    monkeypatch.setattr(
        util, "find_spec", lambda name, *a, **k: None if name == "streamlit" else real_find_spec(name, *a, **k)
    )
    code = cli.main(["dashboard"])
    assert code == 2
    err = capsys.readouterr().err
    assert "streamlit" in err.lower()
    assert "pip install" in err


def test_cli_dashboard_launches_streamlit_against_the_app(monkeypatch, tmp_path, capsys):
    """The command must shell out to `streamlit run dashboard/app.py` and pass the port."""
    from scalper import cli

    captured: dict = {}

    def fake_call(argv, *a, **k):
        captured["argv"] = argv
        return 0

    monkeypatch.setattr("subprocess.call", fake_call)
    code = cli.main(["dashboard", "--port", "8601", "--address", "127.0.0.1"])
    assert code == 0
    argv = captured["argv"]
    assert argv[1:5] == ["-m", "streamlit", "run", str(APP)]
    assert "--server.port" in argv and "8601" in argv
    assert "--server.address" in argv and "127.0.0.1" in argv
    assert "http://localhost:8601" in capsys.readouterr().out


def test_cli_dashboard_reports_a_missing_app_file(monkeypatch, tmp_path, capsys):
    from scalper import cli

    monkeypatch.setattr("subprocess.call", lambda *a, **k: pytest.fail("should not launch"))
    monkeypatch.setattr(cli.Path, "is_file", lambda self: False)
    code = cli.main(["dashboard"])
    assert code == 2
    assert "not found" in capsys.readouterr().err
