"""Dashboard data layer.

The Streamlit app is a thin skin over plain functions (`discover`, `load_run`,
`comparison_table`, ...). Those functions are what actually reads your files, so
they are what needs testing — no browser, no Streamlit runtime required.

The module is loaded from its path because `dashboard/` is deliberately not a
package (Streamlit runs it as a script).
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import pandas as pd
import pytest

APP = Path(__file__).resolve().parents[1] / "dashboard" / "app.py"


def _load_app_module():
    spec = importlib.util.spec_from_file_location("scalper_dashboard_app", APP)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def app():
    assert APP.is_file(), "dashboard/app.py is missing"
    return _load_app_module()


